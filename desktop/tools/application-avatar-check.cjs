'use strict';
// Normal Electron application, isolated facility store, no provider calls or Save.
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const driver = require.resolve('./application-check.cjs');
require(driver);
require.cache[driver].exports = { run: async ({ window, profile, output, root }) => {
    await fs.mkdir(output, { recursive: true });
    const source = JSON.parse(await fs.readFile(path.join(profile.dataRoot, 'application-check-source.json'), 'utf8'));
    assert.equal(profile.facilityRoot, source.isolatedFacilityRoot);
    assert.notEqual(path.resolve(profile.facilityRoot), path.resolve(root, '.runtime/facility-layout'));
    const report = { status: 'running', stages: [], pageErrors: [], mutations: [] };
    const save = () => fs.writeFile(path.join(output, 'avatar-check.json'), JSON.stringify(report, null, 2));
    const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
    const stage = async name => { report.stage = name; report.stages.push(name); await save(); };
    const js = code => window.webContents.executeJavaScript(code, true);
    const until = async (code, label, timeout = 90000) => {
        const deadline = Date.now() + timeout;
        while (Date.now() < deadline) { if (await js(code)) return; await delay(100); }
        throw Error(label);
    };
    const app = '_trainFacilityLayoutAuthoringApp';
    const adapter = app + '.workspace.threeAdapter';
    const state = () => js(adapter + '.getWalkthroughState()');
    const key = (type, keyCode) => window.webContents.sendInputEvent({ type, keyCode });
    const tap = async value => { key('keyDown', value); await delay(40); key('keyUp', value); await delay(100); };
    const click = async selector => {
        window.focus(); window.webContents.focus();
        const point = await js('(()=>{const e=document.querySelector(' + JSON.stringify(selector) + '); if(!e||e.disabled)throw Error("Missing control"); const r=e.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)};})()');
        window.webContents.sendInputEvent({ type: 'mouseMove', ...point });
        window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point });
        window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point });
        await delay(150);
    };
    const shot = async name => {
        await delay(150);
        const image = await window.webContents.capturePage(); assert(!image.isEmpty());
        await fs.writeFile(path.join(output, name + '.png'), image.toPNG());
        const bitmap = image.toBitmap(); const colors = new Set();
        for (let i = 0; i < bitmap.length; i += 64) colors.add(bitmap.subarray(i, i + 3).toString('hex'));
        assert(colors.size > 60, 'Nonblank rendered screenshot');
        return { ...image.getSize(), colors: colors.size };
    };
    window.webContents.on('console-message', details => {
        if (details?.level === 'error') report.pageErrors.push(String(details.message).slice(0, 500));
    });
    try {
        await stage('mount-manual');
        window.setTitle('InspectorPro - Isolated avatar verification');
        await until('!!window.' + app + '?.session.getState().loaded', 'manual mount timeout');
        const original = await js(app + '.session.getState()');
        assert.equal(original.layout.placements.length, 827);
        assert.equal(original.baseRevision, source.originalSha256);
        const sourceCopy = path.join(profile.facilityRoot, 'layouts/local/site-local/layouts/' + original.layout.layoutId + '.json');
        const copyHash = createHash('sha256').update(await fs.readFile(sourceCopy)).digest('hex');
        await js('(()=>{window.__avatarWrites=[];const fetchOriginal=window.fetch;window.fetch=function(input,options){const url=String(input?.url||input);const method=String(options?.method||input?.method||"GET").toUpperCase();if(url.includes("/api/facility-layouts/")&&["POST","PUT","DELETE"].includes(method))window.__avatarWrites.push({url,method});return fetchOriginal.apply(this,arguments);};return true;})()');
        await stage('load-real-3d');
        await click('#trainFacilityLayoutAuthoring [data-view="3d"]');
        await until(adapter + '?.getDiagnostics().pendingLoads===0 && ' + adapter + '?.getDiagnostics().assetGroupCount>0', 'GLB timeout', 150000);
        report.three = await js(adapter + '.getDiagnostics()');
        assert.equal(report.three.degraded, false);
        assert.equal(report.three.placementCount, 827);
        assert(report.three.representationGroups.some(g => ['overview','detail'].includes(g.representation) && g.prototypeMeshCount > 1));
        // Choose a point from existing route geometry. Never author test coordinates into the layout.
        const route = original.layout.routes.find(r => r.label === 'Main Forklift Boulevard');
        const [a, b] = [route.centerline[0], route.centerline.at(-1)];
        const spawn = { x: a.x * 0.7 + b.x * 0.3, y: 0, z: a.z * 0.7 + b.z * 0.3 };
        await js(adapter + '.topView({minimum:{x:' + (spawn.x - 10) + ',y:0,z:' + (spawn.z - 10) + '},maximum:{x:' + (spawn.x + 10) + ',y:8,z:' + (spawn.z + 10) + '}})');
        const overview = await js(adapter + '.getDiagnostics().camera');
        await stage('enter-third-person');
        await click('[data-three-command="avatar-view"]');
        assert.equal((await state()).cameraMode, 'third-person');
        await js(adapter + '.enterWalkthrough({ignoreSelection:true,worldPoint:' + JSON.stringify(spawn) + '})');
        await until(adapter + '.getWalkthroughState().locked', 'real pointer lock unavailable');
        let walk = await state();
        assert(walk.avatar.visible && walk.cameraDistance > 0.75);
        report.entry = walk;
        report.wide = await shot('01-avatar-wide');
        await stage('native-keyboard-gait');
        key('keyDown', 'W');
        await until(adapter + '.getWalkthroughState().avatar.distanceMeters > .3', 'keyboard movement timeout', 15000);
        report.walking = await state();
        assert(report.walking.avatar.distanceMeters > 0.15);
        assert.equal(report.walking.avatar.animation, 'walk');
        assert(Math.abs(report.walking.avatar.leftHip) > 0.001);
        await shot('02-avatar-walking');
        key('keyUp', 'W');
        await until(adapter + '.getWalkthroughState().avatar.animation === "idle"', 'idle gait timeout', 5000);
        const stopped = await state();
        await delay(250);
        assert.deepEqual((await state()).position, stopped.position);
        const beforeView = stopped.position;
        await tap('C');
        assert.equal((await state()).cameraMode, 'first-person');
        assert.equal((await state()).avatar.visible, false);
        assert.deepEqual((await state()).position, beforeView);
        await shot('03-first-person');
        await tap('C');
        assert.equal((await state()).cameraMode, 'third-person');
        assert.deepEqual((await state()).position, beforeView);
        await stage('route-and-drone');
        const goal = { x: beforeView.x + 2, z: beforeView.z };
        const planned = await js(adapter + '.navigateWalkthroughToPoint(' + JSON.stringify(goal) + ')');
        assert(planned.ok && Math.abs(planned.distance - 2) < 1e-6);
        await until(adapter + '.getWalkthroughState().route.reason === "arrived"', 'route failed', 10000);
        await until(adapter + '.getWalkthroughState().avatar.animation === "idle"', 'route idle failed', 5000);
        const beforeDrone = (await state()).position;
        await tap('G');
        const drone = await js(adapter + '.getDroneState()');
        assert(drone.active && drone.locked);
        const droneCamera = await js(adapter + '.getDiagnostics().camera.position');
        assert(Math.hypot(droneCamera.x - beforeDrone.x, droneCamera.z - beforeDrone.z) < 0.001);
        assert.equal((await state()).avatar, null);
        await tap('G');
        assert((await state()).active && (await state()).avatar);
        // Use the API to exit: Escape is reserved by Chromium for pointer lock.
        await js(adapter + '.exitWalkthrough("test-exit")');
        assert.deepEqual(await js(adapter + '.getDiagnostics().camera'), overview);
        assert.equal((await state()).avatar, null);
        await stage('narrow-and-lifecycle');
        window.setSize(900, 700); await delay(500);
        await click('[data-three-command="walkthrough"]');
        await until(adapter + '.getWalkthroughState().locked', 'narrow pointer lock');
        report.narrowWalk = await state();
        report.narrow = await shot('04-avatar-narrow');
        await js(app + '.workspace._setViewMode("plan")');
        assert.equal((await state()).active, false);
        assert.equal((await state()).avatar, null);
        await js(app + '.workspace._setViewMode("3d")');
        await click('[data-three-command="walkthrough"]');
        await until(adapter + '.getWalkthroughState().locked', 'reentry pointer lock');
        assert((await state()).avatar);
        await js(adapter + '.exitWalkthrough("finished")');
        const final = await js(app + '.session.getState()');
        for (const name of ['layout','draftRevision','baseRevision','selection','history','historyCursor','dirty']) assert.deepEqual(final[name], original[name], name);
        report.mutations = await js('window.__avatarWrites');
        assert.deepEqual(report.mutations, []);
        assert.equal(createHash('sha256').update(await fs.readFile(sourceCopy)).digest('hex'), copyHash);
        assert.equal(createHash('sha256').update(await fs.readFile(source.originalPath)).digest('hex'), source.originalSha256);
        report.originalUnchanged = true; report.isolatedSavedCopyUnchanged = true;
        report.status = 'passed'; await stage('complete');
    } catch (error) {
        report.status = 'failed'; report.error = error.stack;
        try { report.failureState = await state(); await shot('failure'); } catch (_) {}
        throw error;
    } finally { await save(); }
} };
require('../src/application-main.cjs');
